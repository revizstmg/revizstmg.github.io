import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {preparer,etatEleve,attendreAccueil} from './eleve.js'

for(const [theme,width] of [['light',1024],['dark',1440]])test('accès communauté toujours visibles sur ordinateur : '+theme,async({page},info)=>{
 const errors=await preparer(page,etatEleve({theme}))
 await page.setViewportSize({width,height:900})
 await page.goto('./#/accueil');await attendreAccueil(page)
 const cookie=page.getByRole('button',{name:'OK',exact:true});if(await cookie.isVisible())await cookie.click()
 const nav=page.locator('header .desktop-quick-links')
 await expect(nav).toBeVisible();await expect(nav.getByRole('link')).toHaveCount(4)
 for(const [label,path] of [['Ma classe','/classe'],['Amis','/amis'],['Boutique','/boutique'],['Classement','/classement']]){
  const link=nav.getByRole('link',{name:label,exact:true})
  await expect(link).toBeInViewport();await expect(link).toHaveAttribute('href','#'+path)
  await link.click();await expect(page).toHaveURL(new RegExp('#'+path+'$'))
  await expect(link).toHaveAttribute('aria-current','page')
  await expect(nav.locator('[aria-current=page]')).toHaveCount(1)
 }
 await page.waitForFunction(()=>document.getAnimations().every(a=>a.playState!=='running'||a.effect?.getComputedTiming().iterations===Infinity))
 expect((await new AxeBuilder({page}).include('.desktop-quick-links').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
 await page.screenshot({path:info.outputPath('navigation-'+theme+'.png')})
 await page.setViewportSize({width:390,height:844});await expect(nav).not.toBeVisible()
 expect(errors).toEqual([])
})

for(const [theme,width] of [['light',1024],['dark',1440]])test('menu burger ordinateur à gauche : '+theme,async({page},info)=>{
 const errors=await preparer(page,etatEleve({theme}))
 await page.setViewportSize({width,height:900});await page.goto('./#/cours');await attendreAccueil(page)
 const cookie=page.getByRole('button',{name:'OK',exact:true});if(await cookie.isVisible())await cookie.click()
 const trigger=page.getByRole('button',{name:'Menu',exact:true})
 await expect(trigger).toBeInViewport()
 const box=await trigger.boundingBox(),brand=await page.locator('.mobile-header-row>a').first().boundingBox()
 expect(box.x).toBeLessThan(brand.x);expect(box.y).toBeLessThan(50)
 await trigger.focus();await page.keyboard.press('Enter')
 const menu=page.getByRole('dialog',{name:'Menu',exact:true}),close=menu.getByRole('button',{name:'Fermer',exact:true})
 await expect(menu).toBeVisible();await expect(close).toBeFocused();await expect(trigger).toHaveAttribute('aria-expanded','true')
 const rect=await menu.boundingBox();expect(rect.x).toBe(16);expect(rect.width).toBe(420);expect(rect.y+rect.height).toBeLessThanOrEqual(900)
 for(const label of ['Accueil','Cours','Réviser','Bac blanc','Ma classe','Amis','Boutique','Classement','Paramètres'])await expect(menu.getByRole('link',{name:label,exact:true})).toBeVisible()
 await expect(menu.locator('[aria-current=page]')).toContainText('Cours')
 expect(await page.evaluate(()=>document.body.style.overflow)).toBe('hidden')
 for(let i=0;i<30;i++)await page.keyboard.press('Tab')
 expect(await menu.evaluate(el=>el.contains(document.activeElement))).toBe(true)
 expect((await new AxeBuilder({page}).include('.site-menu-panel').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
 await close.click();await expect(menu).toHaveCount(0);await expect(trigger).toBeFocused()
 await trigger.click();await menu.getByRole('link',{name:'Boutique',exact:true}).click()
 await expect(page).toHaveURL(/#\/boutique$/);await expect(menu).toHaveCount(0)
 await trigger.click();await page.mouse.click(width-8,450)
 await expect(menu).toHaveCount(0);await expect(trigger).toBeFocused()
 await trigger.click();await page.setViewportSize({width:390,height:844})
 await expect(menu).toBeVisible();await expect(menu).toBeInViewport()
 await page.setViewportSize({width,height:900});await expect(menu).toBeVisible()
 await menu.locator('.site-menu-scroll').evaluate(el=>el.scrollTop=0)
 await page.screenshot({path:info.outputPath('menu-desktop-'+theme+'.png')})
 await page.keyboard.press('Escape');await expect(menu).toHaveCount(0);await expect(trigger).toBeFocused()
 await expect(trigger).toHaveAttribute('aria-expanded','false')
 expect(await page.evaluate(()=>document.body.style.overflow)).not.toBe('hidden')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
 expect(errors).toEqual([])
})
