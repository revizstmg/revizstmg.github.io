async function prepareNote(page,handler){
 const errors=await preparer(page)
 await page.route('https://*.supabase.co/functions/v1/examen-blanc',handler)
 await page.goto('./#/mes-notes');await attendreAccueil(page)
 await page.getByLabel('Note sur 20',{exact:true}).fill('11')
 await page.getByLabel('Matière',{exact:true}).selectOption('maths')
 await page.getByLabel('Chapitre',{exact:true}).selectOption('math-c3')
 await page.getByLabel('Question(s) manquée(s) · facultatif').fill('Q3 : je ne sais pas dériver une somme')
 return errors
}
const valid=b=>({status:'ready',summary:'La difficulté déclarée concerne la dérivation.',weaknesses:[{chapterId:b.courses[0].id,skill:'Dérivation',evidence:'Q3 déclarée comme manquée.',advice:'Revoir la dérivée d’une somme.'}],exercises:Array.from({length:3},(_,i)=>({chapterId:b.courses[0].id,skill:'Dérivation',question:`Dérive f(x) = x² + ${i}x.`,correction:`f’(x) = 2x + ${i}.`}))})
test('annuler, retrouver le brouillon puis réessayer sans double envoi',async({page})=>{
 let first=true,calls=0
 const errors=await prepareNote(page,async route=>{
  calls++
  if(first){first=false;await new Promise(r=>setTimeout(r,1200));return route.abort().catch(()=>{})}
  return route.fulfill({contentType:'application/json',body:JSON.stringify({study:valid(route.request().postDataJSON())})})
 })
 const button=page.getByRole('button',{name:'Préparer mon bilan et mes exercices',exact:true})
 await button.click();await expect(page.getByRole('button',{name:'Annuler l’analyse'})).toBeEnabled()
 await expect.poll(()=>calls).toBe(1)
 await page.getByRole('button',{name:'Annuler l’analyse'}).click()
 await expect(page.getByRole('alert')).toContainText('Analyse annulée');await expect(button).toBeEnabled()
 await page.reload();await attendreAccueil(page)
 await expect(page.getByLabel('Question(s) manquée(s) · facultatif')).toHaveValue('Q3 : je ne sais pas dériver une somme')
 await expect(page.getByLabel('Matière',{exact:true})).toHaveValue('maths')
 await button.click();await expect(page.getByText('La difficulté déclarée concerne la dérivation.')).toBeVisible()
 await expect(page.getByRole('link',{name:'Revoir la notion dans le cours'})).toHaveAttribute('href',/#\/subject\/maths\/theme\/math-c3\/chapter\/0/)
 await page.reload();await attendreAccueil(page)
 await expect(page.getByText('La difficulté déclarée concerne la dérivation.')).toBeVisible()
 await page.getByRole('button',{name:'Ajouter',exact:true}).click()
 expect((await etat(page)).notesClasse[0].revision.exercises).toHaveLength(3)
 expect(calls).toBe(2);expect(errors).toEqual([])
})
