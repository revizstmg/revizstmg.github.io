test('apparence : modes explicites et réglage du système sans changer les autres préférences',async({page})=>{
 await preparer(page,etatEleve({theme:'light',studyLanguages:['en','de']}))
 await page.emulateMedia({colorScheme:'dark'})
 await page.goto('./#/parametres?rubrique=apparence&reglage=apparence');await attendreAccueil(page)
 await page.locator('main').getByRole('button',{name:'Selon l’appareil',exact:true}).click()
 await expect(page.locator('html')).toHaveClass(/dark/)
 expect((await etat(page)).theme).toBeNull()
 await page.locator('main').getByRole('button',{name:'Clair',exact:true}).click()
 await expect(page.locator('html')).not.toHaveClass(/dark/)
 expect((await etat(page)).studyLanguages).toEqual(['en','de'])
})
