import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {preparer,attendreAccueil,etatEleve,etat} from './eleve.js'
for(const [theme,width] of [['light',320],['dark',1280]])test(`paramètres par rubriques : ${theme}`,async({page},info)=>{
 const errors=await preparer(page,etatEleve({theme}))
 await page.setViewportSize({width,height:850});await page.goto('./#/parametres');await attendreAccueil(page)
 const main=page.locator('main'),root=main.locator('.settings-categories')
 await expect(root.getByRole('link')).toHaveCount(7)
 await expect(main.locator('input,select,textarea')).toHaveCount(0)
 await expect(main.getByRole('button',{name:/Supprimer mon compte/})).toHaveCount(0)
 expect((await new AxeBuilder({page}).include('main').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([])
 await page.screenshot({path:info.outputPath('parametres-rubriques-'+theme+'.png'),fullPage:true})
 await root.getByRole('link',{name:'Mon compte',exact:true}).click()
 await expect(main.getByRole('heading',{level:1,name:'Mon compte'})).toBeFocused()
 await expect(main.locator('input')).toHaveCount(0)
 await expect(main.locator('.settings-subcategories').getByRole('link')).toHaveCount(2)
 await main.getByRole('link',{name:'Sécurité',exact:true}).click()
 await expect(page.getByLabel('Nouveau mot de passe',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Prénom',{exact:true})).toHaveCount(0)
 await expect(page.getByRole('checkbox')).toHaveCount(0)
 await page.reload();await attendreAccueil(page)
 await expect(page.getByLabel('Nouveau mot de passe',{exact:true})).toBeVisible()
 await main.getByRole('link',{name:/Mon compte/}).click()
 await main.getByRole('link',{name:/Paramètres/}).click()
 await main.getByRole('link',{name:'Confidentialité et données',exact:true}).click()
 await expect(main.getByRole('button',{name:/Supprimer mon compte/})).toHaveCount(0)
 await main.locator('.settings-subcategories').getByRole('link',{name:'Télécharger mes données',exact:true}).click()
 await expect(main.getByRole('button',{name:/Télécharger mes données/})).toBeVisible()
 await expect(main.getByRole('button',{name:/Supprimer mon compte/})).toHaveCount(0)
 const download=page.waitForEvent('download');await main.getByRole('button',{name:/Télécharger mes données/}).click()
 expect((await download).suggestedFilename()).toContain('revizstmg-mes-donnees-')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
test('réglages de révision et de données séparés, ancien accès conservé',async({page})=>{
 const errors=await preparer(page)
 await page.goto('./#/parametres?rubrique=revision&reglage=langues');await attendreAccueil(page)
 await expect(page.getByRole('group',{name:'Tes langues étudiées'})).toBeVisible()
 await expect(page.getByRole('button',{name:/Télécharger mes données/})).toHaveCount(0)
 await page.goto('./#/parametres?rubrique=revision&reglage=examen')
 await expect(page.getByLabel('Date de mon bac',{exact:true})).toBeVisible()
 await page.getByLabel('Date de mon bac',{exact:true}).fill('2027-06-15')
 expect((await etat(page)).bacDate).toBe('2027-06-15')
 await expect(page.getByRole('checkbox')).toHaveCount(0)
 await page.goto('./#/parametres?rubrique=donnees&reglage=suppression')
 await expect(page.getByRole('button',{name:/Supprimer mon compte/})).toBeVisible()
 await expect(page.getByRole('button',{name:/Télécharger mes données/})).toHaveCount(0)
 page.once('dialog',d=>d.dismiss());await page.getByRole('button',{name:/Supprimer mon compte/}).click()
 expect((await etat(page)).profile.firstName).toBe('Léa')
 await page.goto('./#/parametres?rubrique=inconnue')
 await expect(page).toHaveURL(/#\/parametres$/)
 await page.goto('./#/moi');await page.locator('main').getByRole('link',{name:'Réglages',exact:true}).click()
 await expect(page).toHaveURL(/#\/parametres$/)
 expect(errors).toEqual([])
})
