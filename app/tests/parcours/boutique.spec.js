import { test, expect } from '@playwright/test'
import { preparer, attendreAccueil, etat, etatEleve } from './eleve.js'

async function ouvrir(page, extra) {
  const erreurs = await preparer(page, etatEleve(extra))
  await page.goto('./')
  await attendreAccueil(page)
  await page.goto('./#/boutique')
  await expect(page.getByRole('heading', { name: 'Tes efforts ont du style.' })).toBeVisible()
  return erreurs
}

test('collections : achats, équipement, filtres et persistance', async ({ page }) => {
  const erreurs = await ouvrir(page, { xp: 5000, coins: 5000 })
  await page.getByRole('button', { name: 'Collections', exact: true }).click()
  await page.getByRole('button', { name: /Titres/ }).click()
  const titre = page.getByRole('article', { name: 'Esprit curieux', exact: true })
  await titre.getByRole('button', { name: 'Obtenir', exact: true }).click()
  await titre.getByRole('button', { name: 'Équiper', exact: true }).click()
  expect((await etat(page)).customTheme.title).toBe('Esprit curieux')
  expect((await etat(page)).coins).toBe(4800)
  await page.getByRole('button', { name: /Bannières/ }).click()
  const banner = page.getByRole('article', { name: 'Atlantique', exact: true })
  await banner.getByRole('button', { name: 'Obtenir', exact: true }).click()
  await banner.getByRole('button', { name: 'Équiper', exact: true }).click()
  expect((await etat(page)).customTheme.banner).toBe('#28678b')
  await page.getByRole('button', { name: 'Mes objets', exact: true }).click()
  await expect(banner.getByRole('button', { name: '✓ Équipé', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /Tout explorer/ }).click()
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.reload()
  await attendreAccueil(page)
  await page.goto('./#/moi')
  await expect(page.getByText('✦ Esprit curieux', { exact: true })).toBeVisible()
  expect((await etat(page)).owned).toEqual(expect.arrayContaining(['title-curieux', 'banner-atlantique']))
  expect(erreurs).toEqual([])
})

test('pièces insuffisantes, raretés verrouillées, packs et cadeaux uniques', async ({ page }) => {
  const erreurs = await ouvrir(page, { xp: 4000, coins: 600, freezes: 0 })
  await page.getByRole('button', { name: 'Collections', exact: true }).click()
  await page.getByLabel('Rechercher un article').fill('Phénix')
  await expect(page.getByRole('article', { name: 'Phénix', exact: true }).getByRole('button')).toBeDisabled()
  await page.getByLabel('Rechercher un article').fill('Réserve de sérénité')
  const pack = page.getByRole('article', { name: 'Réserve de sérénité', exact: true })
  await pack.getByRole('button', { name: 'Obtenir', exact: true }).click()
  await expect(pack.getByRole('button', { name: 'Pièces insuffisantes', exact: true })).toBeDisabled()
  expect((await etat(page)).freezes).toBe(3)
  expect((await etat(page)).coins).toBe(60)
  await page.getByRole('button', { name: 'Récompenses', exact: true }).click()
  const reward = page.getByRole('article', { name: 'Le rythme est pris', exact: true })
  await reward.getByRole('button', { name: 'Récupérer ma récompense', exact: true }).click()
  await expect(reward.getByText('✓ Récompense récupérée')).toBeVisible()
  expect((await etat(page)).freezes).toBe(5)
  await page.reload()
  await attendreAccueil(page)
  await page.getByRole('button', { name: 'Récompenses', exact: true }).click()
  await expect(reward.getByRole('button')).toHaveCount(0)
  expect((await etat(page)).freezes).toBe(5)
  expect(erreurs).toEqual([])
})

test('les mois offerts exigent les résultats et restent des réservations futures', async ({ page }) => {
  const chapters = Object.fromEntries(Array.from({ length: 50 }, (_, i) => [`theme-${i}`, { quiz: 95, games: {} }]))
  const erreurs = await ouvrir(page, { xp: 73500, coins: 4000, chapters })
  await page.screenshot({ path: '/workspace/work/shop-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Récompenses', exact: true }).click()
  for (const name of ['Un mois Premium offert', 'Un mois Ultimate offert']) {
    const article = page.getByRole('article', { name, exact: true })
    await article.getByRole('button', { name: 'Réserver mon mois offert', exact: true }).click()
    await expect(article.getByText('✓ Récompense réservée · à faire vérifier')).toBeVisible()
    await expect(article.getByRole('link', { name: 'Préparer ma demande par e-mail' })).toHaveAttribute('href', /^mailto:revizstmg@gmail.com\?subject=/)
    await expect(article).toContainText('Aucune activation ni facturation aujourd’hui')
  }
  const state = await etat(page)
  expect(state.shopRewards['premium-month'].status).toBe('reserved')
  expect(state.shopRewards['ultimate-month'].status).toBe('reserved')
  expect(state.coins).toBe(4000)
  expect(state.subscription).toBeUndefined()
  await page.reload()
  await attendreAccueil(page)
  await page.getByRole('button', { name: 'Récompenses', exact: true }).click()
  await expect(page.getByText('✓ Récompense réservée · à faire vérifier')).toHaveCount(2)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'À la une', exact: true }).click()
  await page.screenshot({ path: '/workspace/work/shop-desktop.png', fullPage: true })
  expect(erreurs).toEqual([])
})
