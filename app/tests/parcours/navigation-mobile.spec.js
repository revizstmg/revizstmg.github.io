import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {preparer,attendreAccueil,etatEleve,etat} from './eleve.js'
for(const [theme,width,height] of [['light',320,640],['dark',390,844],['light',844,390]])test(`menu principal à gauche, organisé et accessible ${theme} ${width}`,async({page},info)=>{
 const errors=await preparer(page,etatEleve({theme}))
 await page.setViewportSize({width,height});await page.goto('./#/cours');await attendreAccueil(page)
 const cookie=page.getByRole('button',{name:'OK',exact:true});if(await cookie.isVisible())await cookie.click()
 const trigger=page.getByRole('button',{name:'Menu',exact:true})
 const box=await trigger.boundingBox();expect(box.x).toBeLessThan(24);expect(box.y).toBeLessThan(50)
 await trigger.focus();await page.keyboard.press('Enter')
 const menu=page.getByRole('dialog',{name:'Menu',exact:true}),close=menu.getByRole('button',{name:'Fermer',exact:true})
 await expect(menu).toBeVisible();await expect(close).toBeFocused()
 const rect=await menu.boundingBox();expect(rect.x).toBeLessThan(16);expect(rect.y).toBeGreaterThanOrEqual(0);expect(rect.y+rect.height).toBeLessThanOrEqual(height)
 for(const label of ['Accueil','Cours','Réviser','Bac blanc','Ma classe','Amis','Boutique','Classement'])await expect(menu.getByRole('link',{name:label,exact:true})).toBeVisible()
 await expect(menu.locator('[aria-current=page]')).toContainText('Cours')
 expect(await page.evaluate(()=>document.body.style.overflow)).toBe('hidden')
 await page.waitForFunction(()=>document.getAnimations().every(a=>a.playState!=='running'||a.effect?.getComputedTiming().iterations===Infinity))
 expect((await new AxeBuilder({page}).include('.site-menu-panel').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
 expect(await menu.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await menu.getByText('Plus d’outils',{exact:true}).click()
 await expect(menu.getByRole('link',{name:'Atelier de formules',exact:true})).toBeVisible()
 await menu.locator('.site-menu-scroll').evaluate(el=>el.scrollTop=el.scrollHeight)
 await expect(close).toBeInViewport()
 await page.screenshot({path:info.outputPath('menu-'+width+'.png')})
 await close.click();await expect(menu).toHaveCount(0);await expect(trigger).toBeFocused()
 expect(await page.evaluate(()=>document.body.style.overflow)).not.toBe('hidden')
 await trigger.click();await menu.getByRole('link',{name:'Amis',exact:true}).click();await expect(page).toHaveURL(/#\/amis$/);await expect(menu).toHaveCount(0)
 expect(errors).toEqual([])
})
test('choisir et ordonner ses onglets dans le menu, sauvegarde et limites',async({page})=>{
 const errors=await preparer(page)
 await page.setViewportSize({width:390,height:844});await page.goto('./#/accueil');await attendreAccueil(page)
 const cookie=page.getByRole('button',{name:'OK',exact:true});if(await cookie.isVisible())await cookie.click()
 await page.getByRole('button',{name:'Menu',exact:true}).click()
 const menu=page.getByRole('dialog',{name:'Menu',exact:true})
 await menu.getByRole('button',{name:'Choisir mes onglets',exact:true}).click()
 const editor=menu.locator('.navigation-tabs-editor')
 await expect(editor.getByLabel('Ajouter un onglet',{exact:true})).toBeDisabled()
 await editor.getByRole('button',{name:'Retirer Réviser',exact:true}).click()
 await editor.getByLabel('Ajouter un onglet',{exact:true}).selectOption('amis')
 await editor.getByRole('button',{name:'Monter Amis',exact:true}).click()
 const expected=['accueil','cours','bacblanc','amis','profil']
 expect((await etat(page)).tabs).toEqual(expected)
 expect(await editor.locator('li').evaluateAll(els=>els.map(el=>el.dataset.tabId))).toEqual(expected)
 await page.waitForFunction(()=>document.getAnimations().every(a=>a.playState!=='running'||a.effect?.getComputedTiming().iterations===Infinity))
 expect((await new AxeBuilder({page}).include('.site-menu-panel').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
 await page.keyboard.press('Escape');await expect(menu).toHaveCount(0)
 await expect(page.locator('.mobile-bottom-nav')).toContainText('Amis')
 await page.reload();await attendreAccueil(page);expect((await etat(page)).tabs).toEqual(expected)
 await page.getByRole('button',{name:'Menu',exact:true}).click();await menu.getByRole('button',{name:'Choisir mes onglets',exact:true}).click()
 for(const name of ['Accueil','Cours','Bac blanc'])await editor.getByRole('button',{name:'Retirer '+name,exact:true}).click()
 await expect(editor.locator('li')).toHaveCount(2)
 await expect(editor.getByRole('button',{name:/^Retirer /}).first()).toBeDisabled()
 await editor.getByRole('button',{name:'Rétablir les onglets par défaut',exact:true}).click()
 expect((await etat(page)).tabs).toBeNull()
 await expect(editor.locator('li')).toHaveCount(5)
 await menu.getByRole('button',{name:'Retour',exact:false}).click();await expect(menu.getByRole('link',{name:'Cours',exact:true})).toBeVisible()
 await page.setViewportSize({width:1280,height:900});await expect(menu).toHaveCount(0)
 expect(errors).toEqual([])
})
