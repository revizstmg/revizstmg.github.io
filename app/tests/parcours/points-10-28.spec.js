test('deux onglets : le changement de compte et la déconnexion changent aussi l’interface',async({page,context})=>{
 await preparer(page)
 const old={token:'old-token',refresh:'old-refresh',user:{id:'00000000-0000-4000-8000-000000000001'},expires_at:9999999999}
 await page.addInitScript(s=>localStorage.setItem('stmg_session',JSON.stringify(s)),old)
 await page.goto('./#/accueil');await expect(page.locator('main h1')).toBeVisible()
 const other=await context.newPage();await preparer(other)
 await other.goto('./#/accueil')
 await page.route('**/rest/v1/profiles?**',route=>route.fulfill({contentType:'application/json',body:JSON.stringify([{id:'new',name:'Paul Professeur',role:'prof',email:'prof@test.fr',level:'terminale-stmg',specialty:'gestion-finance',progress:{xp:800}}])}))
 // Le changement doit actualiser le rôle affiché, pas seulement le jeton partagé.
 await other.evaluate(()=>localStorage.setItem('stmg_session',JSON.stringify({token:'new-token',user:{id:'new'},expires_at:9999999999})))
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('stmg_progress_v2')).account?.role)).toBe('prof')
 await other.evaluate(()=>localStorage.removeItem('stmg_session'))
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('stmg_progress_v2')).account)).toBeNull()
 await other.close()
})
test('QCM de classe : un envoi échoué survit au rechargement puis est renvoyé',async({page})=>{
 const owner='00000000-0000-4000-8000-000000000001'
 const errors=await preparer(page,etatEleve({classCode:'classe-test'}))
 await page.addInitScript(owner=>localStorage.setItem('stmg_session',JSON.stringify({token:'test-token',refresh:'test-refresh',user:{id:owner},expires_at:9999999999})),owner)
 let failing=true,sent=[]
 await page.route('https://*.supabase.co/**',route=>{
  const request=route.request(),url=new URL(request.url())
  if(url.pathname.endsWith('/class_quiz_result') && request.method()==='POST'){
   if(failing)return route.fulfill({status:503,contentType:'application/json',body:'{}'})
   sent.push(request.postDataJSON());return route.fulfill({status:201,contentType:'application/json',body:'[]'})
  }
  if(url.pathname.endsWith('/class_quiz'))return route.fulfill({contentType:'application/json',body:JSON.stringify([{id:'quiz-test',title:'QCM réseau',status:'approved',questions:[{q:'Combien font 2 + 2 ?',choices:['4','3'],answer:0,explain:'2 + 2 = 4.'}]}])})
  return route.fulfill({contentType:'application/json',body:'[]'})
 })
 await page.goto('./#/classe');await attendreAccueil(page)
 await page.getByRole('button',{name:/QCM/}).click()
 await page.getByRole('button',{name:'Jouer',exact:true}).click()
 await page.getByRole('button',{name:/^[AB] 4$/}).click()
 await page.getByRole('button',{name:/Voir mon score/}).click()
 await expect(page.getByText('Résultat conservé sur cet appareil.',{exact:false})).toBeVisible()
 expect(await page.evaluate(owner=>JSON.parse(localStorage.getItem(`stmg_quiz_outbox_v1:${owner}`)).length,owner)).toBe(1)
 await page.reload();await attendreAccueil(page)
 await expect(page.getByRole('button',{name:'Renvoyer mes résultats',exact:true})).toBeVisible()
 failing=false
 await page.getByRole('button',{name:'Renvoyer mes résultats',exact:true}).click()
 await expect.poll(()=>sent.length).toBe(1)
 expect(sent[0][0]).toMatchObject({quiz_id:'quiz-test',device_id:owner,score:1,total:1})
 await expect.poll(()=>page.evaluate(owner=>JSON.parse(localStorage.getItem(`stmg_quiz_outbox_v1:${owner}`)).length,owner)).toBe(0)
 expect(errors).toEqual([])
})
