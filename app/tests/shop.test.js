import { test, expect } from 'vitest'
import { SHOP_ITEMS, SHOP_LEVELS, SHOP_REWARDS, purchaseItem, equipItem, rewardProgress, collectReward } from '../src/data/shop.js'
import { levelFromXp, mergeProgress, restoreAccountState } from '../src/store.jsx'
const state = (extra = {}) => ({ xp: 0, coins: 1000, owned: [], freezes: 0, shopRewards: {}, chapters: {}, account: { id: 'test' }, ...extra })
const progress = (count, score) => Object.fromEntries(Array.from({ length: count }, (_, i) => [`theme-${i}`, { quiz: score }]))

test('le catalogue conserve les anciens objets et propose cinq catégories', () => {
  expect(SHOP_ITEMS.length).toBeGreaterThanOrEqual(48)
  expect(new Set(SHOP_ITEMS.map((i) => i.id)).size).toBe(SHOP_ITEMS.length)
  expect(new Set(SHOP_ITEMS.map((i) => i.category)).size).toBe(5)
  expect(SHOP_ITEMS.find((i) => i.id === 'av-fox').price).toBe(150)
})
test('acheter débite le prix du catalogue, une seule fois pour un objet permanent', () => {
  const initial = state()
  const bought = purchaseItem(initial, 'av-fox')
  expect(bought.coins).toBe(850)
  expect(bought.owned).toContain('av-fox')
  expect(purchaseItem(bought, 'av-fox')).toBe(bought)
  expect(purchaseItem(initial, 'inconnu')).toBe(initial)
  expect(purchaseItem(state({ coins: 149 }), 'av-fox').owned).toEqual([])
})
test('les raretés et cadeaux ne sont pas achetables avant leur palier', () => {
  const initial = state({ coins: 10000 })
  expect(purchaseItem(initial, 'av-phenix')).toBe(initial)
  expect(purchaseItem(state({ xp: 50000 }), 'title-confirme').owned).toEqual([])
})
test('les packs donnent la bonne quantité et les objets équipés ont un effet', () => {
  expect(purchaseItem(state({ xp: 4000 }), 'freeze-pack').freezes).toBe(3)
  expect(purchaseItem(state({ xp: 4000 }), 'freeze-pack-5').freezes).toBe(5)
  const initial = state({ owned: ['banner-atlantique', 'title-curieux'] })
  expect(equipItem(initial, 'banner-atlantique').customTheme.banner).toBe('#28678b')
  expect(equipItem(initial, 'title-curieux').customTheme.title).toBe('Esprit curieux')
  expect(equipItem(initial, 'av-fox')).toBe(initial)
  expect(equipItem(state({ owned: ['pal-nebuleuse'] }), 'pal-nebuleuse').theme).toBe('dark')
})
test('les niveaux historiques sont conservés, avec des caps à 20 et 30', () => {
  expect(SHOP_LEVELS.slice(0, 12)).toEqual([0, 100, 250, 450, 700, 1000, 1400, 1900, 2500, 3200, 4000, 5000])
  expect(levelFromXp(20000).level).toBe(20)
  expect(levelFromXp(73500).level).toBe(30)
  for (let i = 1; i < SHOP_LEVELS.length; i++) expect(SHOP_LEVELS[i]).toBeGreaterThan(SHOP_LEVELS[i - 1])
})
test('un mois Premium demande des XP et vingt tests distincts à 90 %', () => {
  const reward = SHOP_REWARDS.find((r) => r.id === 'premium-month')
  expect(rewardProgress(state({ xp: 20000, chapters: progress(20, 89) }), reward).eligible).toBe(false)
  expect(rewardProgress(state({ xp: 19999, chapters: progress(20, 90) }), reward).eligible).toBe(false)
  expect(rewardProgress(state({ xp: 20000, chapters: progress(19, 100) }), reward).eligible).toBe(false)
  const good = state({ xp: 20000, chapters: progress(20, 90) })
  const claimed = collectReward(good, reward.id)
  expect(claimed.shopRewards[reward.id].status).toBe('reserved')
  expect(claimed.coins).toBe(good.coins)
  expect(claimed.subscription).toBeUndefined()
  expect(collectReward(claimed, reward.id)).toBe(claimed)
  expect(collectReward({ ...good, account: null }, reward.id).shopRewards).toEqual({})
})
test('Ultimate exige trente tests à 95 % et le niveau 30', () => {
  const reward = SHOP_REWARDS.find((r) => r.id === 'ultimate-month')
  expect(rewardProgress(state({ xp: 73500, chapters: progress(30, 94) }), reward).eligible).toBe(false)
  expect(rewardProgress(state({ xp: 73500, chapters: progress(29, 100) }), reward).eligible).toBe(false)
  expect(rewardProgress(state({ xp: 73500, chapters: progress(30, 95) }), reward).eligible).toBe(true)
  expect(rewardProgress(state({ xp: 73500, chapters: progress(30, Infinity) }), reward).eligible).toBe(false)
})
test('les cadeaux sont uniques, équipables ensuite et conservés lors de la fusion', () => {
  const once = collectReward(state({ xp: 700 }), 'regulier')
  expect(once.freezes).toBe(2)
  expect(collectReward(once, 'regulier')).toBe(once)
  const gift = collectReward(state({ xp: 3200 }), 'confirme')
  expect(gift.owned).toContain('title-confirme')
  expect(equipItem({ ...gift, customTheme: {} }, 'title-confirme').customTheme.title).toBe('Réviseur confirmé')
  expect(mergeProgress(state(), gift).shopRewards.confirme.status).toBe('collected')
})
test('les titres et bannières équipés ne passent pas au compte suivant', () => {
  const previous = state({ customTheme: { title: 'Élite STMG', banner: '#123456', avatar: '🦊', accent: '#888888' } })
  const next = restoreAccountState(previous, { id: 'nouveau', role: 'eleve', name: 'Élève' }, { user: { id: 'nouveau' } })
  expect(next.customTheme.title).toBeUndefined()
  expect(next.customTheme.banner).toBeUndefined()
  expect(next.customTheme.avatar).toBeUndefined()
  expect(next.customTheme.accent).toBe('#888888')
})

test('une ancienne copie ne rembourse pas les achats après synchronisation', () => {
  const before = state({ xp: 4000, coins: 1000, shopWalletUpdatedAt: 100 })
  const after = purchaseItem(before, 'av-fox')
  expect(mergeProgress(after, before).coins).toBe(850)
  expect(mergeProgress(before, after).coins).toBe(850)
  const consumed = { ...after, freezes: 0, shopWalletUpdatedAt: after.shopWalletUpdatedAt + 1 }
  expect(mergeProgress(consumed, { ...after, freezes: 5 }).freezes).toBe(0)
})
